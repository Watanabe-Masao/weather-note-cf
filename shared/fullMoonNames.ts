// 満月の呼び名の説明（2026-11-20 渡辺さんの資料「満月の名前と由来・詳細解説」から、毎年使える部分だけ）。
// その年だけのこと（月食・ブルームーン・いちばん近い満月など）は文にせず、shared/moon.ts の計算で出す
// （fullMoonFacts）。呼び名の決め方は fullMoonName（アメリカの農事暦〔Old Farmer's Almanac〕の呼び方）。
// 呼び名は主に北米の季節に基づく文化的な名前で、月の色や明るさが変わるわけではない（自然科学の事実と混同しない）。

export interface FullMoonNameInfo {
  /** fullMoonName が返す名前（カタカナ）。 */
  name: string;
  en: string;
  /** 一言（例：狼の月 · 冬の遠吠え）。 */
  gloss: string;
  /** 象徴（3つ）。 */
  symbols: string[];
  /** 名前の由来。 */
  origin: string[];
  /** 自然・天文学との関係。 */
  nature: string[];
  /** この満月が象徴するもの。 */
  meaning: string;
  /** カードやロゴのモーダルに出す短い紹介（1文）。 */
  short: string;
  /**
   * 季節の物語（2026-11-20 渡辺さんの資料「満月の物語」から、毎年使える部分だけ）：情景 → 自然の営み → 名前の由来 →
   * 月に込められた意味。満月の物語（src/ui/MoonStory.tsx）で一段落ずつ出す。その年だけのこと（月食など）は入れない。
   */
  tale?: {
    tagline: string;
    lines: string[];
  };
  /**
   * 絵本の形（2026-11-21 渡辺さん「満月の物語」絵本制作基盤、承認C）：場面のある満月だけが持つ。絵本の本文（第1層）、
   * 物語のあとがき（第2層）、自然と科学（第3層）を分けて持つ。無い満月は tale のまま（全作品を同時に変えない）。
   * 本文・あとがき・自然と科学の根拠は Project の「事実・出典管理シート」。
   */
  book?: StoryBook;
}

/** 絵本の形（FullMoonNameInfo.book）。 */
export interface StoryBook {
  /**
   * 絵本のページ。1ページ＝場面の1コマ（場面のコマの数と同じ）。lines は縦書きで順に出す行。rest はそのページを
   * 読み終えてから次へ進むまでの余白（秒、絵だけを見せる時間）。
   */
  pages: { lines: string[]; rest?: number }[];
  /** 物語のあとがき（名前の由来と文化的な背景）。 */
  afterword: { title: string; paragraphs: string[] };
  /** 自然と科学（物語の背景の事実）。heading の無い節は段落だけ。 */
  science: { title: string; sections: { heading?: string; text: string }[] };
}

